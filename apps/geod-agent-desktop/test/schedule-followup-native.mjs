import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
const evidence=new URL('../../../docs/implementation/evidence/',import.meta.url);
const rpc=async(command,args={})=>{const value=await(await fetch('http://127.0.0.1:1421/rpc',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({command,args})})).json();if(value.error)throw value.error;return value.value;};
const previous=JSON.parse(readFileSync(new URL('schedule-agent-model-2026-10-02.json',evidence),'utf8'));
const conversationId=previous.conversation,planId=previous.trace.find(t=>t.name==='schedules_create').args.planId;
const run=(await rpc('schedules_runs',{conversationId})).find(r=>r.runId===previous.nativeRunAfterModelTurn[0].runId);
assert.equal(run.state,'succeeded');
const quality=(await rpc('artifacts_inspect',{jobId:run.jobId})).quality;
assert.equal(quality.status,'complete');assert.equal(quality.missingTiles,0);
const raster=await rpc('test_native_raster',{jobId:run.jobId});assert(raster.dataTile.nonzeroValues>0);
const created=await rpc('schedules_create',{conversationId,planId,name:'文件范围影像 · 模板归属验收',nextRunAt:new Date(Date.now()+86400000).toISOString(),repeatSeconds:null,maxRetries:1,executionId:randomUUID()});
assert.equal(created.templatePlanId,planId);
await rpc('schedules_set_enabled',{scheduleId:created.scheduleId,enabled:false});
const saved=(await rpc('schedules_list',{conversationId})).find(s=>s.scheduleId===created.scheduleId);
assert.equal(saved.enabled,false);assert.equal(saved.templatePlanId,planId);
const report={verifiedAt:new Date().toISOString(),conversationId,planId,run,quality,raster,template:saved,pass:true};
writeFileSync(new URL('schedule-followup-native-2026-10-02.json',evidence),JSON.stringify(report,null,2));
writeFileSync(new URL('schedule-template-fixture.json',import.meta.url),JSON.stringify({conversationId,planId},null,2));
console.log('Actual scheduled output verified; template ID persisted; future test trigger paused.');
